def upsert_clinics() -> int:
    init_db()
    db = SessionLocal()
    try:
        for raw in DEMO_CLINICS:
            payload = dict(raw)
            enrich_payload_affordability(payload)
            clinic = db.get(Clinic, payload["id"])
            if clinic:
                for key, value in payload.items():
                    setattr(clinic, key, value)
            else:
                db.add(Clinic(**payload))
        db.commit()
        return len(DEMO_CLINICS)
    finally:
        db.close()


if __name__ == "__main__":
    count = upsert_clinics()
    print(f"Seeded or updated {count} demonstration clinics.")
